// The generated worklet bundles must match their sources.
//
// WHY THIS TEST EXISTS. `public/clock-processor.js` is built from
// `src/clock/*.js` by `tools/build-clock-worklet.mjs`, and
// `audioWorklet.addModule()` loads the BUILT file. Editing a source without
// rebuilding changes nothing at runtime, and nothing says so: the page boots,
// the tests pass against the sources, and the behaviour is the old one.
//
// That is not hypothetical. Adding `source_ref` to the clock processor for
// E3-09 looked like it had simply not worked — the clock followed the
// external tempo in `clock.get_tempo()` while its beat kept advancing at the
// old 90 bpm, because the main-thread mirror had the new code and the worklet
// did not. Twenty minutes went into the wrong half of the system.
//
// The check is the build tool's own concatenation, repeated. If the two ever
// diverge, the test is wrong and the build tool is right — but they cannot
// diverge silently, which is the point.

import { describe, expect, it } from "vitest";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(__dirname, "..");

function concat(dir: string, parts: string[], banner: string): string {
  let out = banner;
  for (const name of parts) {
    const src = fs.readFileSync(path.join(ROOT, dir, name), "utf8");
    out += `\n// ---- ${name} ${"-".repeat(Math.max(0, 60 - name.length))}\n`;
    out += src.replace(/^export\s+/gm, "");
  }
  return out;
}

describe("the clock worklet bundle", () => {
  it("is what the current sources build to", () => {
    const banner =
      "// GENERATED by tools/build-clock-worklet.mjs from src/clock/.\n" +
      "// Do not edit: edit the sources and run `npm run clock`.\n";
    const expected = concat("src/clock", ["scheduler.js", "ring.js", "core.js", "processor.js"], banner);
    const actual = fs.readFileSync(path.join(ROOT, "public", "clock-processor.js"), "utf8");
    // The message matters more than the assertion: a failure here looks like
    // a mystery at runtime and like one line here.
    expect(actual, "public/clock-processor.js is stale — run `npm run clock`").toBe(expected);
  });
});
