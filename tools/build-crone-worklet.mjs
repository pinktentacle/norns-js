// Build the crone AudioWorklet into one classic script.
//
// Same shape as tools/build-clock-worklet.mjs and for the same reason:
// `audioWorklet.addModule()` loads a CLASSIC script, where `import` is a
// syntax error. Three parts go in:
//
//   crone-classic.js   emscripten's glue, built with EXPORT_ES6=0
//   events.js          the record layout, shared with the main thread
//   processor.js       the AudioWorkletProcessor
//
// The wasm does NOT go in. An AudioWorkletGlobalScope has no `fetch` and no
// `atob`, so the two usual answers both fail; the main thread fetches
// crone.wasm and hands the bytes over in `processorOptions`. That also keeps
// the 230 KB binary a separate cacheable file instead of 307 KB of base64
// re-parsed on every worklet load.
//
//   node tools/build-crone-worklet.mjs            # report
//   node tools/build-crone-worklet.mjs --write    # write public/

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BUILD = path.join(ROOT, "src", "crone", "build");
const SRC = path.join(ROOT, "src", "crone");
const PUBLIC = path.join(ROOT, "public");
const OUT = path.join(PUBLIC, "crone-worklet.js");
const WASM_IN = path.join(BUILD, "crone.wasm");
const WASM_OUT = path.join(PUBLIC, "crone.wasm");

const PARTS = [
  { file: path.join(BUILD, "crone-classic.js"), name: "crone-classic.js", generated: true },
  { file: path.join(SRC, "events.js"), name: "events.js" },
  { file: path.join(SRC, "processor.js"), name: "processor.js" },
];

for (const p of [...PARTS.map((p) => p.file), WASM_IN]) {
  if (!fs.existsSync(p)) {
    console.error(`missing ${path.relative(ROOT, p)} — run \`npm run crone:build\` first`);
    process.exit(1);
  }
}

let out = `// GENERATED by tools/build-crone-worklet.mjs.
// Do not edit: edit src/crone/ and run \`npm run crone:worklet\`.
`;

for (const part of PARTS) {
  const src = fs.readFileSync(part.file, "utf8");
  // An `import` means a source that was not dependency-free, which is a
  // mistake worth failing on rather than stripping. Emscripten's classic
  // output has none; this catches the day someone rebuilds it with
  // EXPORT_ES6=1 by accident and gets a worklet that fails to parse with no
  // useful message.
  if (/^\s*import[\s{(]/m.test(src)) {
    console.error(`${part.name} has an import; a classic worklet script cannot have one`);
    process.exit(1);
  }
  out += `\n// ---- ${part.name} ${"-".repeat(Math.max(0, 56 - part.name.length))}\n`;
  // Only the keyword goes; the declarations stay, so everything lands in one
  // scope. emscripten's glue is left exactly as emitted.
  out += part.generated ? src : src.replace(/^export\s+/gm, "");
}

// A worklet that loads but registers nothing is a node constructor that
// throws later, somewhere else. Check here instead.
if (!/registerProcessor\(\s*["']crone["']/.test(out)) {
  console.error('the bundle does not registerProcessor("crone")');
  process.exit(1);
}

const wasmBytes = fs.statSync(WASM_IN).size;
console.log(
  `${PARTS.length} parts, ${(out.length / 1024).toFixed(1)} KB script + ${(wasmBytes / 1024).toFixed(0)} KB wasm`,
);

if (process.argv.includes("--write")) {
  fs.mkdirSync(PUBLIC, { recursive: true });
  fs.writeFileSync(OUT, out);
  fs.copyFileSync(WASM_IN, WASM_OUT);
  console.log(`wrote ${path.relative(ROOT, OUT)} and ${path.relative(ROOT, WASM_OUT)}`);
}
