#Requires -Version 5.1
<#
.SYNOPSIS
  Fork every upstream norns-js is pinned to, and prove the pins survived.

.DESCRIPTION
  E9-86. The AGPL obliges an offer of the Corresponding Source, and
  `third_party/` is not in this repository — PINS.md names commits in
  repositories nobody here controls. A pinned commit is only as durable as
  somebody else's decision, and this project watched four catalogue
  repositories stop being fetchable in a single afternoon: two renamed or
  deleted, two refused by jsDelivr for size.

  A fork is a complete copy with its history, so every pinned commit stays
  reachable and nobody can force-push it out from under you.

  READ OUT OF PINS.md, not out of a list kept here. PINS.md is generated by
  `tools/pins.mjs` from the trees that were actually built, so a tree added
  or repinned reaches this script without anybody remembering to edit it.

  WHAT IT VERIFIES, and why that is the whole point: after forking, each
  pinned commit is fetched from the fork by its FULL forty characters.
  `git ls-remote` is not the test — it only lists commits a ref points at,
  and every pin here is mid-history. An abbreviation is not the test
  either: `git fetch` refuses one. Measured, against the real repository:

    git fetch --depth=1 …/supercollider.git 0c5a96d701be                exit 128
    git fetch --depth=1 …/supercollider.git 0c5a96d701be992627b4…120f0  exit 0

  GitLab has no fork button that reaches GitHub, so Eigen is mirrored with
  `git push --mirror` instead. That one is a real clone and takes a minute.

.PARAMETER Account
  The GitHub account or organisation the forks land in.

.PARAMETER Emsdk
  Also fork emscripten-core/emsdk. Not an obligation — a compiler is a tool,
  not Corresponding Source — but it is what makes the build reproducible,
  and 4.0.18 is pinned because an older one fails in ways that read as bugs
  in this project.

.PARAMETER VerifyOnly
  Skip forking; just check what is already there.

.PARAMETER DryRun
  Say what would happen and do nothing.

.EXAMPLE
  .\tools\fork-upstreams.ps1 -Account pinktentacle -DryRun
  .\tools\fork-upstreams.ps1 -Account pinktentacle -Emsdk
  .\tools\fork-upstreams.ps1 -Account pinktentacle -VerifyOnly
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)]
  [string] $Account,
  [switch] $Emsdk,
  [switch] $VerifyOnly,
  [switch] $DryRun
)

$ErrorActionPreference = "Stop"
$script:Repo = Split-Path -Parent $PSScriptRoot
$script:Problems = @()

# The ref this script puts in each fork so the pin cannot be lost.
$script:PinTag = "norns-js-pin"

function Say([string] $t, [string] $c = "Gray") { Write-Host $t -ForegroundColor $c }
function Head([string] $t) {
  Write-Host ""
  Write-Host $t -ForegroundColor White
  Write-Host ("-" * 74) -ForegroundColor DarkGray
}
function Ok([string] $w, [string] $d) { Write-Host ("  [ok]   {0,-16} {1}" -f $w, $d) -ForegroundColor Green }
function Act([string] $w, [string] $d) { Write-Host ("  [...]  {0,-16} {1}" -f $w, $d) -ForegroundColor Yellow }
function Bad([string] $w, [string] $d) {
  Write-Host ("  [NO]   {0,-16} {1}" -f $w, $d) -ForegroundColor Red
  # Once per repository, not once per phase. The first real run reported
  # "12 unresolved" for six repositories, which reads as twice as much
  # wrong as there was.
  if ($script:Problems -notcontains $w) { $script:Problems += $w }
}

# --- what to fork, read out of PINS.md -------------------------------------

<#
  The generated table, one row per git tree:

    | `norns` | https://github.com/monome/norns.git | `227aa…7300` |
    | `eigen` | https://gitlab.com/libeigen/eigen.git | `3147…1f8c` (`3.4.0`) |

  Anything that is not a github.com or gitlab.com URL is not something this
  can fork, and is skipped rather than guessed at.
#>
function Get-Pins {
  $pinsFile = Join-Path $script:Repo "PINS.md"
  if (-not (Test-Path $pinsFile)) { throw "no PINS.md at $pinsFile — run this from inside a checkout" }

  $rows = @()
  foreach ($line in (Get-Content $pinsFile)) {
    $m = [regex]::Match($line, '^\|\s*`([^`]+)`\s*\|\s*(http[^\s|]+)\s*\|\s*`([0-9a-f]{40})`')
    if (-not $m.Success) { continue }
    $url = $m.Groups[2].Value
    $host_ = ([uri] $url).Host
    $slug = ([uri] $url).AbsolutePath.TrimStart('/') -replace '\.git$', ''
    $rows += [pscustomobject]@{
      Name   = $m.Groups[1].Value
      Url    = $url
      Host   = $host_
      Slug   = $slug
      Commit = $m.Groups[3].Value
    }
  }
  return $rows
}

# --- the one test that matters ---------------------------------------------

<#
  Has GitHub finished assembling the fork?

  `git ls-remote --heads` answers with the branches it has. A fork that is
  still being copied answers with nothing, or errors, and both mean the
  same thing here: not yet.
#>
function Wait-RepoReady([string] $url, [int] $seconds = 90) {
  $deadline = (Get-Date).AddSeconds($seconds)
  $waited = $false
  for (;;) {
    $refs = & git ls-remote --heads $url 2>&1
    if ($LASTEXITCODE -eq 0 -and ($refs | Measure-Object).Count -gt 0) {
      if ($waited) { Write-Host "" }
      return $true
    }
    if ((Get-Date) -gt $deadline) {
      if ($waited) { Write-Host "" }
      return $false
    }
    if (-not $waited) {
      Write-Host "  [...]  waiting           GitHub is still copying it" -ForegroundColor Yellow -NoNewline
      $waited = $true
    }
    Write-Host "." -ForegroundColor DarkGray -NoNewline
    Start-Sleep -Seconds 3
  }
}

function Test-CommitReachable([string] $url, [string] $sha) {
  $probe = Join-Path ([System.IO.Path]::GetTempPath()) ("pincheck-" + [guid]::NewGuid().ToString("N"))
  try {
    & git init --bare -q $probe 2>&1 | Out-Null
    & git -C $probe fetch -q --depth=1 $url $sha 2>&1 | Out-Null
    return ($LASTEXITCODE -eq 0)
  } finally {
    Remove-Item -Recurse -Force $probe -ErrorAction SilentlyContinue
  }
}

# --- go --------------------------------------------------------------------

Write-Host ""
Write-Host "norns-js — forking the upstreams into $Account" -ForegroundColor Cyan
if ($DryRun) { Write-Host "DRY RUN — nothing will be created" -ForegroundColor Magenta }

if ($null -eq (Get-Command gh -ErrorAction SilentlyContinue)) {
  Bad "gh" "the GitHub CLI is not installed — .\tools\setup-windows.ps1 -Role publish"
  exit 1
}
& gh auth status 2>&1 | Out-Null
if ($LASTEXITCODE -ne 0) {
  Bad "gh auth" "not signed in — run: gh auth login"
  exit 1
}

$pins = Get-Pins
if ($pins.Count -eq 0) { throw "PINS.md has no git trees with a full commit id — regenerate it: npm run pins" }

# emsdk is opt-in, so it is filtered here rather than left out of PINS.md.
$wanted = $pins | Where-Object { $Emsdk -or $_.Name -ne "emsdk" }

Head ("Pinned trees: {0} of {1} in PINS.md" -f $wanted.Count, $pins.Count)
foreach ($p in $wanted) { Say ("  {0,-16} {1}  {2}" -f $p.Name, $p.Slug, $p.Commit.Substring(0, 12)) "DarkGray" }

# --- fork ------------------------------------------------------------------

if (-not $VerifyOnly) {
  Head "Forking"
  foreach ($p in $wanted) {
    $mine = "$Account/$($p.Name)"

    & gh repo view $mine 2>&1 | Out-Null
    if ($LASTEXITCODE -eq 0) {
      Ok $p.Name "$mine already exists"
      continue
    }

    if ($DryRun) {
      if ($p.Host -eq "github.com") { Act $p.Name "would fork $($p.Slug)" }
      else { Act $p.Name "would MIRROR $($p.Url) (not GitHub — a real clone)" }
      continue
    }

    if ($p.Host -eq "github.com") {
      # All branches. The web form's "Copy the default branch only" is
      # ticked by default, and that is exactly how a mid-history pin goes
      # missing; `gh repo fork` takes the lot.
      #
      # OUTPUT CAPTURED AND REPRINTED ON FAILURE. The first run of this
      # against a real account reported six "fork failed" and nothing else:
      # gh's own line scrolled past, and the reason went with it.
      # NO `--remote` HERE. gh refuses it the moment a repository argument
      # is given — "the `--remote` flag is unsupported when a repository
      # argument is provided" — and it refuses the whole command, so every
      # one of these silently did nothing until the output above was being
      # printed. It is a BOOLEAN on `repo fork` and a STRING on
      # `repo create` (the remote's name), which is how it came to be
      # written here at all.
      #
      # `--default-branch-only=false` is the default and is passed anyway:
      # it is the one flag that would quietly cost a mid-history pin, and a
      # default is a thing that can change.
      Act $p.Name "fork $($p.Slug)"
      $out = & gh repo fork $p.Slug --clone=false --default-branch-only=false 2>&1 | Out-String
      if ($LASTEXITCODE -ne 0) {
        Bad $p.Name "fork failed"
        foreach ($l in ($out -split "`r?`n")) { if ($l.Trim()) { Say ("         gh: " + $l.Trim()) "DarkGray" } }
        continue
      }
      if ($out.Trim()) { Say ("         gh: " + $out.Trim()) "DarkGray" }
    } else {
      # GitLab, and there is no cross-host fork. A bare mirror carries every
      # ref, which is what makes the pin reachable afterwards.
      Act $p.Name "mirror $($p.Url) — a real clone, this takes a minute"
      $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("$($p.Name)-mirror-" + [guid]::NewGuid().ToString("N") + ".git")
      try {
        & git clone --mirror $p.Url $tmp
        if ($LASTEXITCODE -ne 0) { Bad $p.Name "clone --mirror failed"; continue }
        & gh repo create $mine --public --description "mirror of $($p.Url) for norns-js"
        if ($LASTEXITCODE -ne 0) { Bad $p.Name "gh repo create failed"; continue }
        & git -C $tmp push --mirror "https://github.com/$mine.git"
        if ($LASTEXITCODE -ne 0) { Bad $p.Name "push --mirror failed"; continue }
      } finally {
        Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
      }
    }
  }
}

# --- verify ----------------------------------------------------------------

Head "Is each pinned commit reachable in your copy?"

if ($DryRun) {
  Say "  skipped — nothing was created" "DarkGray"
} else {
  foreach ($p in $wanted) {
    $mine = "https://github.com/$Account/$($p.Name).git"

    # WAIT FOR IT. "Forking a Repository happens asynchronously. You may
    # have to wait a short period of time before you can access the git
    # objects" — GitHub's own words, in the REST documentation for creating
    # a fork. `gh repo fork` returns as soon as the request is accepted.
    #
    # Measured against a real account: eigen passed and all six forks
    # failed, and eigen is the one this script does NOT fork — it pushes a
    # mirror itself, synchronously, so the objects are there when the push
    # returns. Every GitHub fork was still being assembled.
    if (-not (Wait-RepoReady $mine)) {
      Bad $p.Name "$Account/$($p.Name) has no refs yet — GitHub is still copying it. Run with -VerifyOnly in a minute."
      continue
    }

    # A REF WE PUT THERE OURSELVES, which is the only kind that cannot be
    # argued with.
    #
    # A fork is reachable-by-SHA only as far as its own refs reach, and what
    # refs a fork ends up with is GitHub's business, not ours — it copies
    # branches and tags, not `refs/pull/*`, and a branch deleted upstream
    # later takes its history with it. All six pins here sit mid-history on
    # develop, main or master, so in principle a complete fork has them; in
    # practice this check kept saying otherwise.
    #
    # So stop depending on it. `third_party/<name>` is a clone that provably
    # contains the commit — it is what the binaries were built from — so push
    # a tag from there straight into the fork. After that the pin is held by
    # a ref with our name on it, for as long as the fork exists, whatever
    # upstream does to its branches.
    $local = Join-Path $script:Repo "third_party\$($p.Name)"
    if (-not (Test-CommitReachable $mine $p.Commit) -and (Test-Path (Join-Path $local ".git"))) {
      $has = & git -C $local cat-file -e "$($p.Commit)^{commit}" 2>&1
      if ($LASTEXITCODE -eq 0) {
        Act $p.Name "pinning it with a tag pushed from third_party\$($p.Name)"
        $out = & git -C $local push $mine "$($p.Commit):refs/tags/$script:PinTag" 2>&1 | Out-String
        if ($LASTEXITCODE -ne 0) {
          foreach ($l in ($out -split "`r?`n")) { if ($l.Trim()) { Say ("         git: " + $l.Trim()) "DarkGray" } }
        }
      }
    }

    if (Test-CommitReachable $mine $p.Commit) {
      Ok $p.Name ("{0}  reachable" -f $p.Commit.Substring(0, 12))
    } else {
      Bad $p.Name ("{0} is NOT reachable in $Account/$($p.Name), and the tag push did not " -f $p.Commit.Substring(0, 12) +
        "fix it. Either third_party\$($p.Name) is not here — this needs the build machine — " +
        "or the push was refused; its output is above. Nothing needs deleting.")
    }
  }
}

# --- what happened ---------------------------------------------------------

Head "Summary"
if ($script:Problems.Count -gt 0) {
  Write-Host ("  {0} unresolved: {1}" -f $script:Problems.Count, ($script:Problems -join ", ")) -ForegroundColor Red
  exit 1
}
if ($DryRun) {
  Write-Host "  dry run finished. Run it again without -DryRun to create them." -ForegroundColor Magenta
} else {
  Write-Host "  every pinned commit is reachable in $Account." -ForegroundColor Green
  Write-Host ""
  Say "  Paste these into the release notes alongside the table from PINS.md:" "DarkGray"
  foreach ($p in $wanted) { Say ("    https://github.com/$Account/$($p.Name)") "DarkGray" }
}
Write-Host ""
