# --- tools -----------------------------------------------------------------

function Need([string] $exe, [string] $why) {
  $c = Get-Command $exe -ErrorAction SilentlyContinue
  if ($null -eq $c) {
    Say ("no {0} — {1}" -f $exe, $why) "Red"
    Say "Run: .\tools\setup-windows.ps1 -Role build" "DarkGray"
    exit 1
  }
  return $c.Source
}

function Find-GitBash {
  $gitExe = Get-Command "git" -ErrorAction SilentlyContinue
  if ($null -ne $gitExe) {
    $root = Split-Path -Parent (Split-Path -Parent $gitExe.Source)
    $c = Join-Path $root "bin\bash.exe"
    if (Test-Path $c) { return $c }
  }
  foreach ($c in @("C:\Program Files\Git\bin\bash.exe", "C:\Program Files (x86)\Git\bin\bash.exe")) {
    if (Test-Path $c) { return $c }
  }
  return $null
}

function Sha256([string] $path) {
  return (Get-FileHash $path -Algorithm SHA256).Hash.ToLower()
}

# CURL.EXE AND NOT curl. In PowerShell `curl` is an alias for
# Invoke-WebRequest, which takes different arguments entirely. `-L` is not
# optional either: without it a redirect leaves a 0-byte file.
function Fetch([string] $url, [string] $to) {
  $dir = Split-Path -Parent $to
  if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
  & curl.exe -sSL --fail --retry 3 --retry-delay 2 -o $to $url
  if ($LASTEXITCODE -ne 0) { throw "download failed: $url" }
  if (-not (Test-Path $to)) { throw "nothing at $to after downloading $url" }
}

function MB([string] $path) {
  return "{0:N1} MB" -f ((Get-Item $path).Length / 1MB)
}

