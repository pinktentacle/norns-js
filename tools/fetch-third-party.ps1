.PARAMETER NoFidelity
  Leave out `freetype-2104` and `pixman-0400`. `pins:check` will then
  report the tree as stale, because PINS.md lists them.

.PARAMETER Force
  Re-fetch a tree that is already there. Deletes it first.

.PARAMETER DryRun
  Print the plan, the URLs and the sizes, and fetch nothing.

.EXAMPLE
  .\tools\fetch-third-party.ps1 -DryRun
  .\tools\fetch-third-party.ps1
  .\tools\fetch-third-party.ps1 -Account pinktentacle
  .\tools\fetch-third-party.ps1 -Only supercollider -Force
#>
