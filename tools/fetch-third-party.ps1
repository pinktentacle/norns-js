<#
.SYNOPSIS
  Put `third_party/` on a machine that has none of it.

.DESCRIPTION
  E9-96. `third_party/` is 2.7 GB of other people's code and is not in this
  repository. Until now the only instruction for getting it was "the other
  sixteen are in PINS.md", which is true and is not a procedure: eight git
  trees at exact commits with their submodules, and ten directories that
  are not clones at all.

  WHERE EACH ONE COMES FROM WAS SCATTERED. The git trees are in PINS.md,
  which is generated and reliable. The rest was in comments inside the
  build scripts (`fftw`, `portedplugins` and its sha256), in a working
  paper (`docs/11-MISSING.md` for the four single-plugin repositories, and
  the renamed account that makes three of them 404 under the name the
  scripts themselves use), and two were nowhere at all ''' cairo and pixman
  were identified from the directory names inside the tarballs. All of it
  is in the table below now, with a sha256 for every file that has a fixed
  one.

  WHAT IT DOES NOT FETCH, and why:

    emsdk          `setup-windows.ps1 -Role build` clones and activates it.
                   Doing it twice would be two 3 GB downloads.
    cmake, ninja   `third_party/cmake` and `third_party/ninja` are the LAST
                   fallback in `tools/sclang/build.sh`, after PATH and
                   after the winget package directory. The setup script
                   installs both, so the fallback is never reached.
    emforge/       `sysroot` and `probe` are what is left of a P0 spike
                   that asked whether emscripten-forge's prebuilt cairo
                   could be used. It could not ''' it needs a patched
                   2023-era emsdk ''' and cairo is built from source here.
                   No build script reads them. `emforge/dl` is kept,
                   because it is the download cache the build scripts' own
                   documented recipes name.

  THE TWO FIDELITY TREES COME TOO. `freetype-2104` and `pixman-0400` are
  read only by `tools/screen/build-freetype-2104.sh` and
  `build-pixman-0400.sh`, which build the SAME `fingerprint.c` against
  norns' own library versions so the two transcripts can be diffed —
  evidence rather than a build input, and 3 MB. They were opt-in until the
  first real run: `PINS.md` lists every directory under `third_party/`, so
  a tree without them can never satisfy `pins:check`. `-NoFidelity` leaves
  them out and makes that check say stale.

.PARAMETER Account
  Clone the git trees from `https://github.com/<account>/<name>.git`
  instead of from upstream ''' the forks `tools/fork-upstreams.ps1` made.
  That is what the forks are FOR: a pin nobody can fetch only documents.
  If the pinned commit is not in the fork, the `norns-js-pin` tag that
  script pushes is tried next.

.PARAMETER Only
  One step by name. `-Only` with no match lists the names.

.PARAMETER PatchOnly
  Apply `patches/` to trees that are already here and do nothing else. For
  a tree fetched before E9-97, when this script cloned without patching —
  re-cloning SuperCollider to apply a 70 KB diff would be a 500 MB
