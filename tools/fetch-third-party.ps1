  $m = @($steps | Where-Object { $_.Name -eq $Only })
  if ($m.Count -eq 0) {
    Say "no step called '$Only'. The names are:" "Red"
    foreach ($s in $steps) { Say ("  " + $s.Name) }
    exit 1
  }
  $steps = $m
}

function Step-Done($s) {
  if ($Force) { return $false }
  return (Test-Path $s.Makes)
}

Head "before anything"
$gitExe = Need "git" "the eight upstream trees are git clones"
Say ("git        " + $gitExe) "Green"
$null = Need "curl.exe" "the release tarballs are plain downloads"
Say "curl.exe   present" "Green"
$null = Need "tar" "built into Windows since 10/1803, and it reads zip as well as tar"
Say "tar        present" "Green"
if (-not (Test-Path $script:Vendor)) { New-Item -ItemType Directory -Force $script:Vendor | Out-Null }
Say ("third_party " + $script:Vendor) "Green"
if ($Account -ne "") { Say ("forks      github.com/" + $Account) "Green" }

Head "the plan"
foreach ($s in $steps) {
  $state = "fetch"
  if (Step-Done $s) { $state = "skip (present)" }
  $colour = "White"
  if ($state -ne "fetch") { $colour = "DarkGray" }
  Say ("  {0,-17} {1,-15} {2}" -f $s.Name, $state, $s.Why) $colour
}
Say ""
Say "  About 2.7 GB in all, most of it supercollider and its submodules." "DarkGray"
if ($NoFidelity) { Say "  -NoFidelity: freetype-2104 and pixman-0400 left out, so pins:check will say stale." "DarkYellow" }

if ($DryRun) {
  Say ""
  Say "-DryRun: nothing was fetched." "DarkYellow"
  exit 0
}

# --- doing it --------------------------------------------------------------

foreach ($s in $steps) {
  if (Step-Done $s) {
    Say ""
    Say ("skipped " + $s.Name + " — " + $s.Makes + " is there") "DarkGray"
    $script:Skipped += $s.Name
    continue
  }
  Head $s.Name
  Say $s.Why "DarkGray"
  $started = Get-Date

  if ($s.Kind -eq "git") {
    $p = $s.Pin
    $dir = Join-Path $script:Vendor $p.Name
    if ($Force -and (Test-Path $dir)) { Remove-Item -Recurse -Force $dir }

    $url = $p.Url
    if ($Account -ne "") { $url = "https://github.com/$Account/$($p.Name).git" }
    Say ("clone $url") "DarkGray"
    & git clone $url $dir
    if ($LASTEXITCODE -ne 0) { Say ("clone failed: " + $url) "Red"; exit 1 }

    # THE COMMIT AND NOT THE BRANCH. A branch moves; `PINS.md` names the
    # forty characters the build was made from, and `pins:check` compares
    # against exactly that.
    & git -C $dir checkout --quiet $p.Commit
    if ($LASTEXITCODE -ne 0) {
      if ($Account -eq "") { Say ("no commit " + $p.Commit + " in " + $url) "Red"; exit 1 }
      # A fork that was copied before the commit existed, or a fork of a
      # fork. `tools/fork-upstreams.ps1` pushes `norns-js-pin` exactly for
      # this, from the tree the binaries were built from.
      Warn ("$($p.Name): the pinned commit is not in your fork — trying the norns-js-pin tag")
      & git -C $dir checkout --quiet "norns-js-pin"
      if ($LASTEXITCODE -ne 0) { Say ("neither the commit nor norns-js-pin is in " + $url) "Red"; exit 1 }
    }

    if ($script:SubTrees.Contains($p.Name)) {
      Say ("submodules (PINS.md names some for this tree)") "DarkGray"
      & git -C $dir submodule update --init --recursive
      if ($LASTEXITCODE -ne 0) { Say ($p.Name + ": submodule update failed") "Red"; exit 1 }
    } else {
      Say ("no submodules — PINS.md names none for this tree, and a clone that") "DarkGray"
      Say ("           initialises them regenerates a PINS.md this one does not match") "DarkGray"
    }

    # THE PATCHES, WHICH ARE NOT OPTIONAL AND ARE EASY TO FORGET.
    #
    # E9-97: this script did not apply them, and the first real run showed
    # exactly why that matters. `build-nopreload.sh` stopped outright —
    # `lang/CMakeLists.txt has no SC_WASM_PRELOAD_CLASSLIB option` — but
    # the sclang build BEFORE it had already run for 72 seconds and said
    # BUILD OK. CMake accepts an unknown `-D` in silence, so an unpatched
    # tree produces a binary that looks right and is not.
    #
    # Left in the working tree rather than committed, which is how
    # `tools/pins.mjs` recognises a patched tree at all: it asks `git diff`.
    # An unpatched clone reports `0 patched`, and that is the signal.
    $patch = Join-Path $script:Repo ("patches" + [IO.Path]::DirectorySeparatorChar + $p.Name + ".patch")
    if (Test-Path $patch) {
        Say ("apply patches/" + $p.Name + ".patch") "DarkGray"
        & git -C $dir apply $patch
        if ($LASTEXITCODE -ne 0) {
            Say ($p.Name + ": patches/" + $p.Name + ".patch did not apply — the clone is at the pinned commit, so this is the patch and not the tree") "Red"
            exit 1
        }
        # INTENT-TO-ADD, and without it the patch is half applied as far as
        # anything that looks can tell. E9-98: 42 of the 43 files in
        # `patches/mi-UGens.patch` are NEW files — the vendored Mutable
        # Instruments DSP — and `git apply` creates them untracked. `git diff`
        # does not report an untracked file, so `tools/pins.mjs` regenerated a
        # 0.6 KB patch from a 698 KB one and `pins:check` called the tree
        # stale. `git add -N` registers them without staging content, which is
        # the state the development tree is in and is why its `git diff` shows
        # all 43.
        & git -C $dir add -N .
        if ($LASTEXITCODE -ne 0) { Say ($p.Name + ": git add -N failed") "Red"; exit 1 }
        $n = (& git -C $dir diff --stat | Select-Object -Last 1)
        Say ("          " + $n.Trim()) "DarkGray"
    }

    $at = (& git -C $dir rev-parse HEAD).Trim()
    if ($at -ne $p.Commit) {
      Warn ("$($p.Name): HEAD is $at, PINS.md says $($p.Commit) — npm run pins:check will say so")
    }
  }

  elseif ($s.Kind -eq "fetch") {
    $d = $s.Dl
    $cache = Join-Path $script:Dl $d.File
    if ($Force -and (Test-Path $cache)) { Remove-Item -Force $cache }
    if (-not (Test-Path $cache)) {
      Say ("get " + $d.Url) "DarkGray"
      Fetch $d.Url $cache
    } else {
      Say ("cached " + $cache) "DarkGray"
    }
    Say ("       " + (MB $cache)) "DarkGray"

    $got = Sha256 $cache
    if ($got -ne $d.Sha) {
      if ($d.ContainsKey("Moving") -and $d.Moving) {
        Warn ("$($s.Name): sha256 differs from the one recorded.")
        Warn ("  recorded $($d.Sha)")
        Warn ("  this one $got")
        Warn ("  A GitHub source archive is regenerated and a branch moves, so this is")
        Warn ("  upstream news rather than a broken download. Record the new value.")
      } else {
        Say ("$($s.Name): sha256 MISMATCH on a file that never changes." ) "Red"
        Say ("  expected $($d.Sha)") "Red"
        Say ("  got      $got") "Red"
        exit 1
      }
    } else {
      Say ("sha256 ok  " + $got.Substring(0, 24) + "…") "DarkGray"
    }

    $into = Join-Path $script:Vendor $d.Into
    if ($Force -and (Test-Path $into)) { Remove-Item -Recurse -Force $into }
    if (-not (Test-Path $into)) { New-Item -ItemType Directory -Force $into | Out-Null }
    # E9-269 — `Exclude`: members left out, for an archive whose test files
    # carry names Windows' tar cannot make (flac's are UTF-8: Prøve.flac,
    # Hebrew, an emoji). Nothing that is built.
    $ex = @()
    if ($d.Exclude) { foreach ($x in $d.Exclude) { $ex += "--exclude=$x" } }
    if ($d.Strip -gt 0) {
      & tar -xf $cache -C $into --strip-components=$($d.Strip) @ex
    } else {
      & tar -xf $cache -C $into @ex
    }
    if ($LASTEXITCODE -ne 0) {
      # Windows' tar cannot even READ those names, so the exclusion cannot
      # match them and the exit status says "error" regardless. Accepted
      # for an entry that declares them, and only when what the build needs
      # is there.
      if ($d.Exclude -and (Test-Path (Join-Path $script:Vendor $d.Makes))) {
        Say ("extract: skipped the members listed in Exclude — " + ($d.Exclude -join ", ")) "DarkYellow"
        # or the script's own exit status would still be tar's
        $global:LASTEXITCODE = 0
      } else {
        Say ("extract failed: " + $cache) "Red"; exit 1
      }
    }

    # The copy the publishing runbook's §3 tarball reads, under the name it
    # reads it by — `cairo.tar.xz`, not `cairo-1.16.0.tar.xz`.
    $keep = Join-Path $script:Vendor $d.Keep
    if ((Resolve-Path $cache).Path -ne (Join-Path $script:Vendor $d.Keep)) {
      $keepDir = Split-Path -Parent $keep
      if (-not (Test-Path $keepDir)) { New-Item -ItemType Directory -Force $keepDir | Out-Null }
      Copy-Item $cache $keep -Force
    }
  }

  elseif ($s.Kind -eq "plugins") {
    $out = Join-Path $script:Vendor "sc-plugins-extra"
    if ($Force -and (Test-Path $out)) { Remove-Item -Recurse -Force $out }
    New-Item -ItemType Directory -Force $out | Out-Null
    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("scx-" + [guid]::NewGuid().ToString("N"))
    New-Item -ItemType Directory -Force $tmp | Out-Null
    try {
      foreach ($pl in $plugins) {
        $tgz = Join-Path $tmp ($pl.Name + ".tar.gz")
        $url = "https://codeload.github.com/$($pl.Repo)/tar.gz/refs/heads/$($pl.Branch)"
        Say ("get " + $url) "DarkGray"
        Fetch $url $tgz
        & tar -xf $tgz -C $tmp
        if ($LASTEXITCODE -ne 0) { Say ("extract failed: " + $tgz) "Red"; exit 1 }

        $src = Join-Path $tmp $pl.Root
        $dst = Join-Path $out $pl.Name
        New-Item -ItemType Directory -Force $dst | Out-Null

        # Only what the build compiles. The .schelp is documentation for an
        # IDE that is not here, and the CMake builds a native .so.
        foreach ($f in @("$($pl.Name).cpp", "$($pl.Name).hpp", "$($pl.Name).sc")) {
          Copy-Item (Join-Path $src "plugins\$($pl.Name)\$f") $dst -Force
        }
        if ($pl.Name -eq "ByteBeat") {
          # ByteBeat is the one with a lexer and a parser of its own, and
          # they are not beside the UGen: headers in include/, sources in
          # src/ beside a main.cpp that is a command-line tool and is left.
          Copy-Item (Join-Path $src "plugins\ByteBeat\ByteBeatController.sc") $dst -Force
          foreach ($f in @("include\ast.hpp", "include\lex.hpp", "include\parse.hpp", "src\lex.cpp", "src\parse.cpp")) {
            Copy-Item (Join-Path $src $f) $dst -Force
          }
          Copy-Item (Join-Path $src "LICENSE") $dst -Force
        }
        # All four ship the same GPL-3 text; one copy at the top.
        if (-not (Test-Path (Join-Path $out "LICENSE"))) {
          Copy-Item (Join-Path $src "LICENSE") (Join-Path $out "LICENSE") -Force
        }
      }
    } finally {
      Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
    }
  }

  $took = [int]((Get-Date) - $started).TotalSeconds
  if (-not (Test-Path $s.Makes)) {
    Say ""
    Say ("{0} finished but {1} is not there." -f $s.Name, $s.Makes) "Red"
    exit 1
  }
  Say ""
  Say ("{0} ok, {1}s" -f $s.Name, $took) "Green"
  $script:Did += $s.Name
}

