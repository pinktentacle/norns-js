# --- patch an existing tree, and nothing else -------------------------------

if ($PatchOnly) {
  Head "patches only"
  $any = $false
  $absent = @()
  foreach ($p in $pins) {
    $dir = Join-Path $script:Vendor $p.Name
    $patch = Join-Path $script:Repo ("patches" + [IO.Path]::DirectorySeparatorChar + $p.Name + ".patch")

    # EVERY PINNED TREE IS LOOKED AT, not only the three with a patch. The
    # submodule reconciliation below applies to all of them — `norns` has no
    # patch and is exactly the tree that needed it.
    if (-not (Test-Path $dir)) {
      Warn ("$($p.Name): not here — fetch it first")
      $absent += $p.Name
      continue
    }
    if (Test-Path $patch) { $any = $true }

    # SUBMODULES FIRST, because a tree fetched before E9-100 has seven of
    # norns' initialised and PINS.md names none: `git diff` is clean either
    # way, but the regenerated document is not.
    $hasSub = @(& git -C $dir submodule status 2>$null)
    $live = @($hasSub | Where-Object { $_ -notmatch '^-' })
    if (-not $script:SubTrees.Contains($p.Name) -and $live.Count -gt 0) {
      Warn ("$($p.Name): $($live.Count) submodule(s) are populated and PINS.md names none — removing them")
      if (-not $DryRun) {
        & git -C $dir submodule deinit --all -f
        if ($LASTEXITCODE -ne 0) { Say ("$($p.Name): submodule deinit failed") "Red"; exit 1 }
      }
    }

    # THEN, REGISTER WHATEVER IS UNTRACKED. A tree patched by an earlier
    # run of this script — before E9-98 — has the new files on disk and
    # invisible to `git diff`, which is a tree that LOOKS patched and
    # regenerates a patch missing 42 of its 43 files. `git add -N` is
    # idempotent and respects .gitignore, so it is safe on a tree that has
    # also been built: SuperCollider's own .gitignore line 32 is `/build*`,
    # which is where `build-wasm/` goes.
    & git -C $dir add -N .
    if ($LASTEXITCODE -ne 0) { Say ("$($p.Name): git add -N failed") "Red"; exit 1 }

    if (-not (Test-Path $patch)) { continue }

    # ALREADY PATCHED IS NOT AN ERROR. `pins.mjs` calls a tree patched when
    # `git diff` is not empty, which is the same test, so this answers the
    # same question the check does.
    $diff = (& git -C $dir diff) | Out-String
    if ($diff.Trim().Length -gt 0) {
      $n = (& git -C $dir diff --stat | Select-Object -Last 1)
      Say ("$($p.Name): already carries changes — " + $n.Trim()) "DarkGray"
      continue
    }
    if ($DryRun) { Say ("$($p.Name): would apply patches/$($p.Name).patch") "DarkYellow"; continue }
    Say ("apply patches/$($p.Name).patch") "DarkGray"
    & git -C $dir apply $patch
    if ($LASTEXITCODE -ne 0) { Say ("$($p.Name): the patch did not apply") "Red"; exit 1 }
    # INTENT-TO-ADD, and without it the patch is half applied as far as
    # anything that looks can tell. E9-98: 42 of the 43 files in
    # `patches/mi-UGens.patch` are NEW files — the vendored Mutable
    # Instruments DSP — and `git apply` creates them untracked. `git diff`
    # does not report an untracked file, so `tools/pins.mjs` regenerated a
    # 0.6 KB patch from a 698 KB one and `pins:check` called the tree
    # stale. `git add -N` registers them without staging content, which is
    # the state the development tree is in and is why its `git diff` shows
    # all 43.
    & git -C $dir add -N .
    if ($LASTEXITCODE -ne 0) { Say ($p.Name + ": git add -N failed") "Red"; exit 1 }
    $n = (& git -C $dir diff --stat | Select-Object -Last 1)
    Say ("          " + $n.Trim()) "Green"
    $script:Did += $p.Name
  }
  if (-not $any) { Say "no patches/*.patch matched a pinned tree." "DarkYellow" }
  if ($absent.Count -gt 0) {
    Say ""
    Say ("Not here: {0}. Run this without -PatchOnly first." -f ($absent -join ", ")) "Red"
    exit 1
  }
  Say ""
  Say "Anything built before this is stale. The SuperCollider one especially:" "DarkYellow"
  Say "  bash tools/sclang/build.sh clean" "DarkGray"
  Say "  .\tools\build-wasm.ps1" "DarkGray"
  exit 0
}

