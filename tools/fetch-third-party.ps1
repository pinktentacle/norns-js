# --- the git trees, read out of PINS.md ------------------------------------
#
# Generated by `tools/pins.mjs` from the trees the build actually used, so a
# tree added or repinned reaches this script without anybody remembering.
# Same parse as `tools/fork-upstreams.ps1`, deliberately: these two run on
# different machines at different times and a shared helper between them is
# a dependency neither needs.
function Get-Pins {
  $pinsFile = Join-Path $script:Repo "PINS.md"
  if (-not (Test-Path $pinsFile)) { throw "no PINS.md at $pinsFile — run this from inside a checkout" }
  $rows = @()
  foreach ($line in (Get-Content $pinsFile)) {
    $m = [regex]::Match($line, '^\|\s*`([^`]+)`\s*\|\s*(http[^\s|]+)\s*\|\s*`([0-9a-f]{40})`')
    if (-not $m.Success) { continue }
    $rows += [pscustomobject]@{
      Name   = $m.Groups[1].Value
      Url    = $m.Groups[2].Value
      Commit = $m.Groups[3].Value
    }
  }
  return $rows
}

# --- which trees get their submodules --------------------------------------
#
# NOT ALL OF THEM, and PINS.md says so in its own words: "These are the ones
# populated in the trees that were built here. Any other submodule in them
# was not needed by anything this project compiles."
#
# E9-100: this script ran `submodule update --init --recursive` on every
# tree, which is the obvious thing and is wrong. `norns` declares seven
# submodules — crone/softcut, third-party/{concurrentqueue,doctest,link,
# lua-cjson} and two more — and none is compiled here: what this project
# takes from norns is `sc/`, `lua/`, `resources/` and one .cc file a
# generator reads. Initialising them downloads megabytes nobody links and,
# worse, puts seven rows in the regenerated PINS.md that the published one
# does not have, so `pins:check` reports a tree that is in fact correct.
#
# The table in PINS.md is the authority, because it is generated from the
# trees the binaries were actually built from. A tree it does not name gets
# no submodules at all.
function Get-SubmoduleTrees {
  $pinsFile = Join-Path $script:Repo "PINS.md"
  $names = New-Object System.Collections.Generic.HashSet[string]
  $inSection = $false
  foreach ($line in (Get-Content $pinsFile)) {
    if ($line -match '^##\s+Submodules') { $inSection = $true; continue }
    if ($inSection -and $line -match '^##\s') { break }
    if (-not $inSection) { continue }
    $m = [regex]::Match($line, '^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|')
    if ($m.Success -and $m.Groups[1].Value -ne "Tree") { [void] $names.Add($m.Groups[1].Value) }
  }
  return $names
}

