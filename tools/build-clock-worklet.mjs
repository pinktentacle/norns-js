// Build the clock AudioWorklet into one classic script.
//
// `audioWorklet.addModule()` loads a CLASSIC script: `import` is a syntax
// error there. So the three dependency-free modules are concatenated in front
// of the processor and their `export` keywords stripped.
//
// Concatenation rather than a bundler because the inputs are deliberately
// import-free — the same files are imported by the tests, and a bundler step
// would be a second way for the two to diverge.
//
//   node tools/build-clock-worklet.mjs            # report
//   node tools/build-clock-worklet.mjs --write    # write public/clock-processor.js

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src", "clock");
const OUT = path.join(ROOT, "public", "clock-processor.js");

const PARTS = ["scheduler.js", "ring.js", "core.js", "processor.js"];

const banner = `// GENERATED by tools/build-clock-worklet.mjs from src/clock/.
// Do not edit: edit the sources and run \`npm run clock\`.
`;

let out = banner;
for (const name of PARTS) {
  const src = fs.readFileSync(path.join(SRC, name), "utf8");
  // Only the `export` keyword goes; the declarations stay, so everything ends
  // up in one scope. An `import` would mean a source that was not
  // dependency-free, which is a mistake worth failing on rather than stripping.
  if (/^\s*import\s/m.test(src)) {
    console.error(`${name} has an import; the worklet cannot have one`);
    process.exit(1);
  }
  out += `\n// ---- ${name} ${"-".repeat(Math.max(0, 60 - name.length))}\n`;
  out += src.replace(/^export\s+/gm, "");
}

console.log(`${PARTS.length} parts, ${(out.length / 1024).toFixed(1)} KB`);
if (process.argv.includes("--write")) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
