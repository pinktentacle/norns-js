// E2-02 — generate the font table from norns' own source.
//
// `screen.font_face(i)` is an INDEX into this list, so one wrong or missing
// entry silently shifts every font after it. Typing the list out produced
// exactly that: the `unscii` fonts are `.pcf` and not `.bdf`, `bmp/unscii-8.pcf`
// is easy to drop between its neighbours, and the last two entries are
// `Particle.ttf` and a SECOND `norns.ttf` — which looks like a mistake until
// you notice `NUM_FONTS` is 69 and the array has to be full.
//
//   node tools/extract-fonts.mjs            # report
//   node tools/extract-fonts.mjs --write    # write src/screen/fonts.h

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCREEN_CC = path.join(ROOT, "third_party/norns/matron/src/hardware/screen.cc");
const RESOURCES = path.join(ROOT, "third_party/norns/resources");
const OUT = path.join(ROOT, "src/screen/fonts.h");

const src = fs.readFileSync(SCREEN_CC, "utf8");

const declared = Number(/#define\s+NUM_FONTS\s+(\d+)/.exec(src)?.[1]);
const fonts = [...src.matchAll(/strcpy\(font_path\[font_idx\+\+\],\s*"([^"]+)"\)/g)].map((m) => m[1]);

const problems = [];
if (!Number.isFinite(declared)) problems.push("could not read NUM_FONTS");
if (fonts.length !== declared) {
  problems.push(`NUM_FONTS is ${declared} but ${fonts.length} strcpy calls were found`);
}

// Which of them actually ship in the resources directory. A missing file is
// not fatal — `init_font_faces` logs and carries on, and only index 0 matters
// for the menu — but it changes what `screen.font_face(i)` does, so it is
// reported rather than discovered later.
const missing = fonts.filter((f) => !fs.existsSync(path.join(RESOURCES, f)));

console.log(`NUM_FONTS ${declared}, entries ${fonts.length}`);
console.log(`  present in resources/  ${fonts.length - missing.length}`);
if (missing.length) {
  console.log(`  MISSING                ${missing.length}: ${missing.join(", ")}`);
}
const dupes = fonts.filter((f, i) => fonts.indexOf(f) !== i);
if (dupes.length) {
  console.log(`  listed more than once  ${[...new Set(dupes)].join(", ")} (upstream does this; the index is what matters)`);
}

if (problems.length) {
  console.error("\nPROBLEMS");
  for (const p of problems) console.error(`  ${p}`);
  process.exit(1);
}

if (process.argv.includes("--write")) {
  const body = fonts.map((f) => `    "${f}",`).join("\n");
  const header = `// Generated by tools/extract-fonts.mjs from
// third_party/norns/matron/src/hardware/screen.cc. Do not edit.
//
// screen.font_face(i) indexes this array, so its ORDER is the API.
// ${fonts.length} entries, matching NUM_FONTS.

#define NORNS_NUM_FONTS ${fonts.length}

static const char *const NORNS_FONT_FILES[NORNS_NUM_FONTS] = {
${body}
};
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
